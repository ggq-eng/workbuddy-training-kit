def sheet(wb, name, title, headers, rows, widths, freeze="A4", note=None):
    ws = wb.create_sheet(name)
    ncol = len(headers)
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncol)
    c = ws.cell(row=1, column=1, value=title)
    c.font = Font(name="微软雅黑", size=14, bold=True, color=NAVY)
    c.alignment = Alignment(horizontal="left", vertical="center")
    ws.row_dimensions[1].height = 30
    if note:
        ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=ncol)
        n = ws.cell(row=2, column=1, value=note)
        n.font = Font(name="微软雅黑", size=9, color="595959")
        n.alignment = Alignment(horizontal="left", vertical="center", wrap_text=True)
        ws.row_dimensions[2].height = 28
    hr = 3
    for i, h in enumerate(headers, 1):
        cell = ws.cell(row=hr, column=i, value=h)
        cell.font = HFONT
        cell.fill = HEADFILL
        cell.alignment = CENTER
        cell.border = BORDER
    ws.row_dimensions[hr].height = 26
    for r_i, row in enumerate(rows):
        r = hr + 1 + r_i
        for i, val in enumerate(row, 1):
            cell = ws.cell(row=r, column=i, value=val)
            cell.font = BFONT
            cell.alignment = WRAP
            cell.border = BORDER
            if r_i % 2 == 1:
                cell.fill = ALTFILL
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = freeze
    ws.sheet_view.showGridLines = False
    return ws


def blank_form(wb, name, title, headers, rows, widths, note=None):
    """生成待填写的空表（含示例行）"""
    ws = sheet(wb, name, title, headers, rows, widths, freeze="A4", note=note)
    return ws


